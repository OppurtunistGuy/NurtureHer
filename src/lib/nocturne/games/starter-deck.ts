import type { CardCategory, GameCard, Heat } from "./types";

function card(
  id: string,
  category: CardCategory,
  heat: Heat,
  title: string,
  extra: Partial<GameCard> = {},
): GameCard {
  return {
    id,
    title,
    category,
    heat,
    kind: category === "rewards" ? "reward" : "task",
    limitTags: [],
    ...extra,
  };
}
